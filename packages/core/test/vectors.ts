import { getAddress, hashDomain, keccak256, toBytes, type Address, type Hex } from "viem";
import { privateKeyToAccount } from "viem/accounts";
import {
  ledgerDomain,
  ledgerStructHash,
  ledgerTypedData,
  memoryDigest,
  memoryDomain,
  memoryStructHash,
  memoryTypedData,
  nsHash,
  parentsHashOf,
  srcHashOf,
  bodyHashOf,
  payeeIdOf,
  type MemoryStruct,
} from "../src/index.js";

/** Fixed inputs shared by the TypeScript test and contracts/test/Vectors.t.sol. */
export async function buildVectors() {
  const chainId = 1983;
  const memoryAnchor: Address = getAddress("0x00000000000000000000000000000000000000a1");
  const tyrellLedger: Address = getAddress("0x00000000000000000000000000000000000000b2");
  const signer = privateKeyToAccount(keccak256(toBytes("tyrell-vector-key")));

  const memory: MemoryStruct = {
    id: "0x0193a1b2c3d47e8f9a0b1c2d3e4f5a6b",
    acct: keccak256(toBytes("tyrell-vector-account")),
    ns: nsHash("steward.mem"),
    lane: 2,
    kind: 4,
    parentsHash: parentsHashOf(["0x00000000000000000000000000000001", "0x00000000000000000000000000000002"]),
    srcHash: srcHashOf([{ t: "erc20", addr: "0x3F43DA82eC9A4f5285F10FaF1F26EcA7319E5DA5" }]),
    turn: "0x0193a1b2c3d47e8f9a0b1c2d3e4f0000",
    refBlock: 12_193_881n,
    bodyHash: bodyHashOf("Rent is 5 QUSDC to the landlord on the 1st."),
    bodyLen: 43,
  };
  const domain = { chainId, memoryAnchor };
  const memorySig = await signer.signTypedData(memoryTypedData(memory, domain));

  const addPayee = {
    payeeId: payeeIdOf("landlord"),
    addr: getAddress("0x7a3f00000000000000000000000000000009c41e"),
    token: getAddress("0x3f43da82ec9a4f5285f10faf1f26eca7319e5da5"),
    capPerTx: 5_000_000n,
    capPerDay: 5_000_000n,
    label: "landlord",
    nonce: 1n,
    deadline: 1_795_770_000n,
  };
  const seedQuarantine = {
    seedType: 2,
    seedValue: `0x${"00".repeat(12)}3f43da82ec9a4f5285f10faf1f26eca7319e5da5` as Hex,
    fromBlock: 0n,
    toBlock: 0n,
    reasonCid: "bafkreiexamplereason",
    nonce: 7n,
    deadline: 1_795_770_000n,
  };
  const releaseQuarantine = { seedId: 3n, reasonCid: "bafkreiexamplerelease", nonce: 2n, deadline: 1_795_770_000n };
  const suspendPayee = { payeeId: payeeIdOf("landlord"), seedId: 3n, nonce: 8n, deadline: 1_795_770_000n };
  const removePayee = { payeeId: payeeIdOf("landlord"), nonce: 3n, deadline: 1_795_770_000n };
  const addPayeeSig = await signer.signTypedData(ledgerTypedData("AddPayee", addPayee, { chainId, tyrellLedger }));

  const str = (o: Record<string, unknown>) =>
    Object.fromEntries(Object.entries(o).map(([k, v]) => [k, typeof v === "bigint" ? v.toString() : v]));

  return {
    note: "Generated by packages/core/scripts/vectors.ts. Do not edit by hand.",
    chainId,
    signer: signer.address,
    memoryAnchor,
    tyrellLedger,
    memory: {
      ...str(memory as unknown as Record<string, unknown>),
      structHash: memoryStructHash(memory),
      domainSeparator: hashDomain({
        domain: { ...memoryDomain(domain), chainId: BigInt(chainId) },
        types: { EIP712Domain: [
          { name: "name", type: "string" },
          { name: "version", type: "string" },
          { name: "chainId", type: "uint256" },
          { name: "verifyingContract", type: "address" },
        ] },
      }),
      digest: memoryDigest(memory, domain),
      signature: memorySig,
    },
    addPayee: { ...str(addPayee), structHash: ledgerStructHash("AddPayee", addPayee), signature: addPayeeSig },
    seedQuarantine: { ...str(seedQuarantine), structHash: ledgerStructHash("SeedQuarantine", seedQuarantine) },
    releaseQuarantine: { ...str(releaseQuarantine), structHash: ledgerStructHash("ReleaseQuarantine", releaseQuarantine) },
    suspendPayee: { ...str(suspendPayee), structHash: ledgerStructHash("SuspendPayee", suspendPayee) },
    removePayee: { ...str(removePayee), structHash: ledgerStructHash("RemovePayee", removePayee) },
    ledgerDomainSeparator: hashDomain({
      domain: { ...ledgerDomain({ chainId, tyrellLedger }), chainId: BigInt(chainId) },
      types: { EIP712Domain: [
        { name: "name", type: "string" },
        { name: "version", type: "string" },
        { name: "chainId", type: "uint256" },
        { name: "verifyingContract", type: "address" },
      ] },
    }),
  };
}
