/**
 * Generates packages/chain/src/abi.ts from Foundry artifacts (run `pnpm contracts:build` first).
 *   pnpm gen:abi
 */
import { readFileSync, writeFileSync } from "node:fs";

const contracts = ["LaneRegistry", "MemoryAnchor", "TyrellLedger", "GuardedVault", "TyrellTestUSD", "AgentRegistry", "AgentNetwork", "TestQieId"];
const lines = ["// Generated by scripts/gen-abi.ts from contracts/out. Do not edit by hand.", ""];
for (const name of contracts) {
  const art = JSON.parse(readFileSync(new URL(`../contracts/out/${name}.sol/${name}.json`, import.meta.url), "utf8"));
  const camel = name[0]!.toLowerCase() + name.slice(1);
  lines.push(`export const ${camel}Abi = ${JSON.stringify(art.abi, null, 2)} as const;`, "");
}
writeFileSync(new URL("../packages/chain/src/abi.ts", import.meta.url), lines.join("\n"));
console.log("wrote packages/chain/src/abi.ts");
